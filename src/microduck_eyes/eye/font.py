GLYPH_W, GLYPH_H = 5, 7


@lru_cache(maxsize=512)
def text_mask(text: str, scale: int = 1, spacing: int = 1) -> np.ndarray:
    """Render `text` (upper-cased) to a float32 alpha mask of shape (7*scale, width)."""
    text = text.upper()
    cols = []
    for i, ch in enumerate(text):
        rows = _G.get(ch, _G[" "])
        g = np.array([[1.0 if c == "#" else 0.0 for c in row] for row in rows], np.float32)
        cols.append(g)
        if i != len(text) - 1:
            cols.append(np.zeros((GLYPH_H, spacing), np.float32))
    mask = np.concatenate(cols, axis=1) if cols else np.zeros((GLYPH_H, 0), np.float32)
    if scale > 1:
        mask = np.kron(mask, np.ones((scale, scale), np.float32))
    return mask


def text_size(text: str, scale: int = 1, spacing: int = 1) -> tuple[int, int]:
    w = len(text) * GLYPH_W + max(len(text) - 1, 0) * spacing
    return w * scale, GLYPH_H * scale
